function genDecodeTabs(startIndexes, lengthBits, elements) {
  const positions = new Uint8Array(0x100);
  for (let i = 0; i < elements; i++) {
    const length = 1 << lengthBits[i];
    for (let index = startIndexes[i]; index < 0x100; index += length) positions[index] = i;
  }
  return positions;
}

export function explode(data) {
  if (!data || data.length < 5) return null;
  const ctype = data[0];
  if (ctype !== 0) return null;
  const dsizeBits = data[1];
  if (dsizeBits < 4 || dsizeBits > 6) return null;
  const dsizeMask = 0xFFFF >> (0x10 - dsizeBits);
  const lengthCodes = genDecodeTabs(LenCodeT, LenBitsT, 16);
  const distPosCodes = genDecodeTabs(DistCodeT, DistBitsT, 64);
  let inPos = 3;
  let bitBuff = data[2];
  let extraBits = 0;
  const inBytes = data.length;
  const waste = (n) => {
    if (n <= extraBits) { extraBits -= n; bitBuff >>>= n; return true; }
    bitBuff >>>= extraBits;
    if (inPos >= inBytes) return false;
    bitBuff = (bitBuff | (data[inPos++] << 8)) >>> 0;
    bitBuff >>>= (n - extraBits);
    extraBits = ((extraBits - n) + 8) >>> 0;
    return true;
  };
  const decodeLit = () => {
    if (bitBuff & 1) {
      if (!waste(1)) return 0x306;
      let lengthCode = lengthCodes[bitBuff & 0xFF];
      if (!waste(LenBitsT[lengthCode])) return 0x306;
      const eb = ExLenBitsT[lengthCode];
      if (eb !== 0) {
        const extra = bitBuff & ((1 << eb) - 1);
        if (!waste(eb)) { if ((lengthCode + extra) !== 0x10E) return 0x306; }
        lengthCode = LenBaseT[lengthCode] + extra;
      }
      return lengthCode + 0x100;
    }
    if (!waste(1)) return 0x306;
    const b = bitBuff & 0xFF;
    if (!waste(8)) return 0x306;
    return b;
  };
  const decodeDist = (repLength) => {
    const code = distPosCodes[bitBuff & 0xFF];
    if (!waste(DistBitsT[code])) return 0;
    let distance;
    if (repLength === 2) {
      distance = (code << 2) | (bitBuff & 0x03);
      if (!waste(2)) return 0;
    } else {
      distance = (code << dsizeBits) | (bitBuff & dsizeMask);
      if (!waste(dsizeBits)) return 0;
    }
    return distance + 1;
  };
  const out = [];
  let next;
  let result = 0;
  while ((result = next = decodeLit()) < 0x305) {
    if (next >= 0x100) {
      const repLength = next - 0xFE;
      const dist = decodeDist(repLength);
      if (dist === 0) { result = 0x306; break; }
      const start = out.length - dist;
      if (start < 0) { result = 0x306; break; }
      for (let k = 0; k < repLength; k++) out.push(out[start + k]);
    } else out.push(next);
  }
  if (result === 0x306) return null;
  return Buffer.from(out);
}
